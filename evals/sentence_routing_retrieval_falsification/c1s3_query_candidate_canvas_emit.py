#!/usr/bin/env python3
"""Patch ``c1s3-breadcrumb-query-candidate-review.canvas.tsx`` from candidate JSON.

Replaces the region between ``BEGIN GENERATED C1S3_CANDIDATE_DETAIL`` /
``END GENERATED C1S3_CANDIDATE_DETAIL`` with a TS ``const`` blob.

Example::

  uv run python -m evals.sentence_routing_retrieval_falsification.c1s3_query_candidate_canvas_emit \\
    --candidates evals/sentence_routing_retrieval_falsification/artifacts/runs/2026-05-05/c1s3_query_candidates.json \\
    --canvas-tsx ~/.cursor/projects/<workspace-slug>/canvases/c1s3-breadcrumb-query-candidate-review.canvas.tsx
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from evals.sentence_routing_retrieval_falsification.cursor_canvas_paths import (
    default_cursor_canvas_path,
    patch_candidate_canvas_paths,
    summarize_candidate_canvas_results,
)

BLOCK_BEGIN = "// BEGIN GENERATED C1S3_CANDIDATE_DETAIL"
BLOCK_END = "// END GENERATED C1S3_CANDIDATE_DETAIL"

_DEFAULT_CANVAS = default_cursor_canvas_path("c1s3-breadcrumb-query-candidate-review.canvas.tsx")


def build_c1s3_candidate_canvas_block(candidates_doc: dict[str, Any]) -> str:
    body = json.dumps(
        {
            "c1s3CandidateSummaryGenerated": {
                "schema": candidates_doc.get("schema"),
                "source_breadcrumb_path": candidates_doc.get("source_breadcrumb_path"),
                "campaign_id": candidates_doc.get("campaign_id"),
                "session_number": candidates_doc.get("session_number"),
                "generated_at_utc": candidates_doc.get("generated_at_utc"),
                "candidate_count": len(list(candidates_doc.get("candidates") or [])),
            },
            "c1s3CandidateRowsGenerated": list(candidates_doc.get("candidates") or []),
        },
        indent=2,
        ensure_ascii=True,
    )
    return (
        f"{BLOCK_BEGIN}\n"
        "// Generated by c1s3_query_candidate_canvas_emit.py — do not hand-edit.\n"
        f"const c1s3CandidateCanvasGenerated = {body} as const;\n"
        f"{BLOCK_END}\n"
    )


def patch_c1s3_candidate_canvas_paths(block: str, paths: list[Path]) -> list[dict[str, Any]]:
    return patch_candidate_canvas_paths(block, paths, begin=BLOCK_BEGIN, end=BLOCK_END)


def refresh_c1s3_candidate_canvases(
    *,
    candidates_doc: dict[str, Any],
    canvas_paths: list[Path],
) -> dict[str, Any]:
    block = build_c1s3_candidate_canvas_block(candidates_doc)
    per_file = patch_c1s3_candidate_canvas_paths(block, canvas_paths)
    return summarize_candidate_canvas_results(canvas_paths, per_file)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--candidates", type=Path, required=True)
    p.add_argument(
        "--canvas-tsx",
        type=Path,
        action="append",
        dest="canvas_tsx_list",
        default=None,
        help=f"Target canvas (repeatable). Default: {_DEFAULT_CANVAS}",
    )
    args = p.parse_args()
    doc = json.loads(args.candidates.read_text(encoding="utf-8"))
    if str(doc.get("schema") or "") != "dmb_breadcrumb_query_candidates_v1":
        raise SystemExit("candidates file must declare schema dmb_breadcrumb_query_candidates_v1")
    targets = [x.expanduser().resolve() for x in (args.canvas_tsx_list or [_DEFAULT_CANVAS])]
    res = refresh_c1s3_candidate_canvases(candidates_doc=doc, canvas_paths=list(targets))
    if res["errors"]:
        raise SystemExit(f"c1s3_query_candidate_canvas_emit: {res['errors']}")
    print(json.dumps(res, indent=2))


if __name__ == "__main__":
    main()
