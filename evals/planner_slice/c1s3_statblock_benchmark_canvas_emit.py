#!/usr/bin/env python3
"""Inject C1S3 scripted statblock benchmark fixture metadata into the Cursor canvas.

Reads the three ``scenario_c1s3_*_statblock_context*.json`` planner fixtures and replaces
the region between ``BEGIN GENERATED C1S3_STATBLOCK_SCENARIO_CANVAS`` /
``END GENERATED C1S3_STATBLOCK_SCENARIO_CANVAS`` in the target canvas.

By default patches the Cursor-managed canvas (see ``cursor_canvas_paths.default_cursor_canvas_path``).

Example::

  uv run python -m evals.planner_slice.c1s3_statblock_benchmark_canvas_emit
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from evals.sentence_routing_retrieval_falsification.cursor_canvas_paths import (
    default_cursor_canvas_path,
    ensure_canvas_file_for_patch,
)

BLOCK_BEGIN = "// BEGIN GENERATED C1S3_STATBLOCK_SCENARIO_CANVAS"
BLOCK_END = "// END GENERATED C1S3_STATBLOCK_SCENARIO_CANVAS"

_CANVAS_BASENAME = "c1s3-statblock-benchmark-scenarios.canvas.tsx"
_DEFAULT_IDE_CANVAS = default_cursor_canvas_path(_CANVAS_BASENAME)

_FIXTURE_NAMES = (
    "scenario_c1s3_pippa_statblock_context.json",
    "scenario_c1s3_bubbles_statblock_context.json",
    "scenario_c1s3_kirfan_missing_context.json",
)


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _fixtures_dir() -> Path:
    return _repo_root() / "evals" / "planner_slice" / "fixtures"


def build_c1s3_statblock_benchmark_payload() -> dict[str, Any]:
    """Structured payload embedded in the canvas (deterministic from fixtures on disk)."""
    scenarios: list[dict[str, Any]] = []
    for name in _FIXTURE_NAMES:
        path = _fixtures_dir() / name
        data = json.loads(path.read_text(encoding="utf-8"))
        ex = data.get("expect") or {}
        sb = ex.get("statblock_args") or {}
        recall = ex.get("recall_npc_context_args") or {}
        scenarios.append(
            {
                "fixtureFilename": name,
                "id": str(data.get("id") or ""),
                "description": str(data.get("description") or ""),
                "userMessage": str(data.get("user_message") or ""),
                "toolNamesInOrder": list(ex.get("tool_names_in_order") or []),
                "statblockStubPresent": bool(data.get("statblock_stub")),
                "recallCampaignId": recall.get("campaign_id"),
                "recallNpcContains": recall.get("npc_contains"),
                "noGenerateStatblock": bool(ex.get("no_generate_statblock")),
                "statblockCreatureContains": sb.get("creature_name_contains"),
                "statblockDescriptionMustContainAll": list(sb.get("description_contains_all") or []),
                "finalTextMustInclude": list(ex.get("final_text_must_include") or []),
            }
        )
    return {
        "generatedAt": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "regenerateCommand": "uv run python -m evals.planner_slice.c1s3_statblock_benchmark_canvas_emit",
        "fixtureDirRel": "evals/planner_slice/fixtures",
        "harnessTest": "tests/test_planner_eval_scenarios.py",
        "canvasBasename": _CANVAS_BASENAME,
        "scenarios": scenarios,
    }


def build_statblock_canvas_block() -> str:
    body = json.dumps(build_c1s3_statblock_benchmark_payload(), indent=2, ensure_ascii=True)
    return (
        f"{BLOCK_BEGIN}\n"
        "// Generated by c1s3_statblock_benchmark_canvas_emit.py — do not hand-edit.\n"
        f"const c1s3StatblockHarnessGenerated = {body} as const;\n"
        f"{BLOCK_END}\n"
    )


def _patch_canvas_text(canvas_text: str, block: str) -> str:
    if BLOCK_BEGIN not in canvas_text or BLOCK_END not in canvas_text:
        raise ValueError(
            f"Canvas must contain {BLOCK_BEGIN!r} and {BLOCK_END!r} markers "
            "(add the empty block once, then re-run this script)."
        )
    pre, rest = canvas_text.split(BLOCK_BEGIN, 1)
    _mid, post = rest.split(BLOCK_END, 1)
    if post.startswith("\n\n"):
        post = post[1:]
    return pre + block + post


def patch_statblock_canvas_paths(block: str, paths: list[Path]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for canvas_path in paths:
        p = canvas_path.expanduser().resolve()
        try:
            ensure_canvas_file_for_patch(p)
            text = p.read_text(encoding="utf-8")
        except OSError as exc:
            out.append({"path": str(p), "error": f"{type(exc).__name__}: {exc}"})
            continue
        try:
            new_text = _patch_canvas_text(text, block)
        except ValueError as exc:
            out.append({"path": str(p), "error": f"{type(exc).__name__}: {exc}"})
            continue
        if new_text != text:
            p.write_text(new_text, encoding="utf-8")
            out.append({"canvas_updated": str(p)})
        else:
            out.append({"canvas_unchanged": str(p)})
    return out


def default_statblock_benchmark_canvas_targets() -> list[Path]:
    """Cursor-managed canvas path for this workspace."""
    return [_DEFAULT_IDE_CANVAS]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--canvas-tsx",
        type=Path,
        action="append",
        dest="canvas_tsx_list",
        default=None,
        help=(
            "Target .canvas.tsx (repeat to patch several files). "
            f"Default: Cursor-managed {_DEFAULT_IDE_CANVAS}."
        ),
    )
    args = p.parse_args()
    targets = [x.expanduser().resolve() for x in (args.canvas_tsx_list or default_statblock_benchmark_canvas_targets())]
    block = build_statblock_canvas_block()
    per_file = patch_statblock_canvas_paths(block, targets)
    errors = [x for x in per_file if "error" in x]
    if errors:
        err_msg = "; ".join(str(e.get("error", e)) for e in errors)
        raise SystemExit(f"c1s3_statblock_benchmark_canvas_emit: canvas patch failed: {err_msg}")
    print(json.dumps({"targets": per_file, "scenario_count": len(_FIXTURE_NAMES)}, indent=2))


if __name__ == "__main__":
    main()
