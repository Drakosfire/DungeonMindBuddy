"""Autogenerate Stage D scenario JSON from Stage C gold fixtures.

Goal: remove manual authoring of ``gold/stage_d_*.json`` when a corresponding
``stage_c_*.json`` fixture already exists.
"""

from __future__ import annotations

import argparse
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

_SLICE_DIR = Path(__file__).resolve().parent
_REPO_ROOT = _SLICE_DIR.parents[1]
_DEFAULT_STAGE_C_GLOB = str(
    _REPO_ROOT / "evals" / "stage_c_npc_candidates_vertical_slice" / "gold" / "stage_c_*.json"
)
_DEFAULT_STAGE_C_SIDECAR_GLOB = str(
    _REPO_ROOT
    / "evals"
    / "stage_c_npc_candidates_vertical_slice"
    / "artifacts"
    / "runs"
    / "*"
    / "stage_c--*.json"
)


def _expand(pattern: str) -> list[Path]:
    p = Path(pattern)
    if p.is_absolute():
        base = Path("/")
        pat = str(p).lstrip("/")
    else:
        base = _REPO_ROOT
        pat = str(p)
    return sorted(base.glob(pat))


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _session_number(session_label: str) -> int | None:
    m = re.search(r"\bSession\s+(\d+)\b", session_label, flags=re.IGNORECASE)
    if not m:
        return None
    try:
        return int(m.group(1))
    except ValueError:
        return None


def _suffix_from_stage_c_id(stage_c_id: str, fallback_name: str) -> str:
    s = stage_c_id.strip()
    if s.startswith("stage_c_"):
        return s[len("stage_c_") :]
    return fallback_name


def _collect_stage_c_output_from_sidecars(*, sidecar_glob: str) -> dict[str, dict[str, Any]]:
    """Best-effort map of ``scenario_id -> latest stage_c_output`` from Stage C sidecars."""
    by_scenario: dict[str, dict[str, Any]] = {}
    for p in _expand(sidecar_glob):
        try:
            payload = _read_json(p)
        except Exception:
            continue
        scenario_id = str(payload.get("scenario_id") or "").strip()
        stage_c_output = payload.get("stage_c_output")
        if not scenario_id or not isinstance(stage_c_output, dict):
            continue
        iso = str(payload.get("iso_utc") or "")
        prev = by_scenario.get(scenario_id)
        if prev is None or iso >= str(prev.get("iso_utc") or ""):
            by_scenario[scenario_id] = {
                "iso_utc": iso,
                "path": str(p),
                "stage_c_output": stage_c_output,
            }
    return by_scenario


def build_stage_d_scenario_from_stage_c(stage_c_gold: dict[str, Any], *, suffix: str) -> dict[str, Any]:
    inp = stage_c_gold.get("input") or {}
    grading_c = stage_c_gold.get("grading") or {}
    expected_min = list(grading_c.get("expected_new_candidates_should_include_at_least_one_of") or [])
    session_label = str(inp.get("session_label") or f"Session {suffix}")
    scenario = {
        "schema": "stage_d_v0.1",
        "scenario_id": f"stage_d_{suffix}",
        "scenario_class": "stage_d_entity_resolution",
        "input": {
            "campaign_id": str(inp.get("campaign_id") or ""),
            "session_label": session_label,
            "session_number": _session_number(session_label),
            "stage_c_output_path": f"evals/stage_d_entity_resolution_vertical_slice/fixtures/stage_c_output_{suffix}.json",
            "stage_a_events_path": str(inp.get("stage_a_events_path") or ""),
            "npc_registry_path": str(inp.get("npc_registry_path") or ""),
            "pc_roster": list(inp.get("pc_roster") or []),
        },
        "grading": {
            "must_not_merge": [],
            "must_merge_clusters": [],
            "must_resolve_unresolved": [],
            "expected_unresolvable_max": 0,
            "expected_proposed_new_records_minimum_slugs": expected_min,
        },
        "notes": (
            "Autogenerated from Stage C gold fixture. "
            "Fine-tune grading.must_not_merge / must_merge_clusters as needed for stricter contracts."
        ),
    }
    return scenario


def autogen_stage_d_scenarios(
    *,
    stage_c_gold_glob: str = _DEFAULT_STAGE_C_GLOB,
    stage_d_gold_dir: Path | None = None,
    stage_d_fixtures_dir: Path | None = None,
    overwrite: bool = False,
    materialize_missing_stage_c_output: bool = False,
    stage_c_sidecar_glob: str = _DEFAULT_STAGE_C_SIDECAR_GLOB,
) -> dict[str, Any]:
    paths = _expand(stage_c_gold_glob)
    out_dir = stage_d_gold_dir or (_SLICE_DIR / "gold")
    fixtures_dir = stage_d_fixtures_dir or (_SLICE_DIR / "fixtures")
    out_dir.mkdir(parents=True, exist_ok=True)
    fixtures_dir.mkdir(parents=True, exist_ok=True)

    generated: list[str] = []
    materialized_fixtures: list[dict[str, str]] = []
    skipped: list[dict[str, str]] = []
    sidecar_outputs = (
        _collect_stage_c_output_from_sidecars(sidecar_glob=stage_c_sidecar_glob)
        if materialize_missing_stage_c_output
        else {}
    )

    for p in paths:
        data = _read_json(p)
        stage_c_id = str(data.get("scenario_id") or p.stem)
        suffix = _suffix_from_stage_c_id(stage_c_id, p.stem)
        stage_c_output_fixture = fixtures_dir / f"stage_c_output_{suffix}.json"
        if not stage_c_output_fixture.is_file():
            if materialize_missing_stage_c_output:
                sidecar = sidecar_outputs.get(stage_c_id)
                stage_c_output = sidecar.get("stage_c_output") if isinstance(sidecar, dict) else None
                if isinstance(stage_c_output, dict):
                    stage_c_output_fixture.write_text(
                        json.dumps(stage_c_output, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8",
                    )
                    materialized_fixtures.append(
                        {
                            "stage_c_gold": str(p),
                            "scenario_id": stage_c_id,
                            "fixture_path": str(stage_c_output_fixture),
                            "source_sidecar_path": str(sidecar.get("path") or ""),
                        }
                    )
                    # Fall through and generate stage_d scenario now that fixture exists.
                else:
                    skipped.append(
                        {
                            "stage_c_gold": str(p),
                            "reason": (
                                f"missing fixture: {stage_c_output_fixture} "
                                f"(no sidecar stage_c_output found for scenario_id={stage_c_id})"
                            ),
                        }
                    )
                    continue
            else:
                skipped.append(
                    {
                        "stage_c_gold": str(p),
                        "reason": f"missing fixture: {stage_c_output_fixture}",
                    }
                )
                continue

        scenario = build_stage_d_scenario_from_stage_c(data, suffix=suffix)
        out_path = out_dir / f"stage_d_{suffix}.json"
        if out_path.exists() and not overwrite:
            skipped.append({"stage_c_gold": str(p), "reason": f"exists: {out_path}"})
            continue
        out_path.write_text(json.dumps(scenario, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        generated.append(str(out_path))

    return {
        "schema": "stage_d_scenario_autogen_v1",
        "iso_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "stage_c_gold_glob": stage_c_gold_glob,
        "generated_count": len(generated),
        "materialized_fixture_count": len(materialized_fixtures),
        "skipped_count": len(skipped),
        "generated": generated,
        "materialized_fixtures": materialized_fixtures,
        "skipped": skipped,
        "materialize_missing_stage_c_output": bool(materialize_missing_stage_c_output),
        "stage_c_sidecar_glob": stage_c_sidecar_glob,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Autogenerate Stage D scenarios from Stage C gold.")
    parser.add_argument("--stage-c-gold-glob", default=_DEFAULT_STAGE_C_GLOB)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--materialize-missing-stage-c-output", action="store_true")
    parser.add_argument("--stage-c-sidecar-glob", default=_DEFAULT_STAGE_C_SIDECAR_GLOB)
    args = parser.parse_args()
    payload = autogen_stage_d_scenarios(
        stage_c_gold_glob=str(args.stage_c_gold_glob),
        overwrite=bool(args.overwrite),
        materialize_missing_stage_c_output=bool(args.materialize_missing_stage_c_output),
        stage_c_sidecar_glob=str(args.stage_c_sidecar_glob),
    )
    print(json.dumps(payload))


if __name__ == "__main__":
    main()
