function joinList(xs: readonly string[]) {
  return xs.length ? xs.join('\n') : 'none';
}

function formatRatio(v: number | null | undefined): string {
  if (v == null || Number.isNaN(Number(v))) {
    return 'n/a';
  }
  return Number(v).toFixed(2);
}

function formatCosine(v: number | null | undefined): string {
  if (v == null || Number.isNaN(Number(v))) {
    return 'n/a';
  }
  return Number(v).toFixed(4);
}

