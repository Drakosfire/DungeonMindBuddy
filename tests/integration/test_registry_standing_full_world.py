def snapshot(creds):
    result = {}
    for key, kind, expected in [
        ("dsn", "native", "benchmark_ingestion_native_e785f5a2e2"),
        ("app_dsn", "app", "benchmark_ingestion_app_e785f5a2e2"),
    ]:
        parts = conninfo_to_dict(creds[key])
        assert parts["host"] in {"localhost", "127.0.0.1"} and parts["port"] == "55447"
        assert parts["dbname"] == expected
        with psycopg.connect(
            make_conninfo(creds[key], options="-c default_transaction_read_only=on")
        ) as c:
            c.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
            assert c.execute("show transaction_read_only").fetchone()[0] == "on"
            other = c.execute(
                "select pid,application_name,state from pg_stat_activity where datname=current_database() and pid<>pg_backend_pid() and backend_type='client backend'"
            ).fetchall()
            assert not other, ("conflicting fixture consumers", other)
            tables = c.execute(
                "select schemaname,tablename from pg_tables where schemaname not in ('pg_catalog','information_schema') order by 1,2"
            ).fetchall()
            result[kind] = {}
            for schema, table in tables:
                hashes = c.execute(
                    sql.SQL(
                        "select encode(sha256(convert_to(to_jsonb(t)::text,'UTF8')),'hex') from {}.{} t order by 1"
                    ).format(sql.Identifier(schema), sql.Identifier(table))
                ).fetchall()
                result[kind][schema + "." + table] = [r[0] for r in hashes]
            if kind == "native":
                result["head"] = c.execute(
                    "select head_revision_id from dungeonmind.knowledge_heads where space_id='elderwyld'"
                ).fetchone()[0]
                result["pins"] = c.execute(
                    "select graph_schema,graph_payload_sha256,revision_payload->'domain_contract_ref',revision_payload->'semantic_profile_ref' from dungeonmind.knowledge_revisions where space_id='elderwyld' and revision_id=%s",
                    (result["head"],),
                ).fetchone()
                result["other_heads"] = c.execute(
                    "select space_id,head_revision_id,updated_at::text,schema_version from dungeonmind.knowledge_heads where space_id<>'elderwyld' order by space_id"
                ).fetchall()
    result["files"] = {
        str(p.relative_to(FIXTURE / "file-state")): hashlib.sha256(
            p.read_bytes()
        ).hexdigest()
        for p in (FIXTURE / "file-state").rglob("*")
        if p.is_file()
    }
    return result


def assert_evolved_baseline(before):
    assert before["head"] == "rev:b216ad0df7d9e0a8bd8533da9dd5c8fd"
    assert before["pins"][0:2] == [
        "dm_vnext_graph_v1",
        "0917ccaa179642ea3ca1df50485d20aa6a2051fc911424dcc9df6b62efed5a50",
    ] or tuple(before["pins"][0:2]) == (
        "dm_vnext_graph_v1",
        "0917ccaa179642ea3ca1df50485d20aa6a2051fc911424dcc9df6b62efed5a50",
    )
    assert (
        before["pins"][2]["descriptor_sha256"]
        == "d12f3a517a37d29a2ba52455d9ae1691bc5e4ff3fd6853b701a9e28e46ec65cd"
    )
    assert (
        before["pins"][3]["descriptor_sha256"]
        == "51ea47ff45bc86ea158939c34a5769e7ee56de3911278d473570e3795edb7e14"
    )
    captured = json.loads((DONOR / "status.json").read_text())
    for kind in ["native", "app"]:
        expected = {
            r["schema"] + "." + r["table"]: r
            for r in captured["databases"][kind]["source_tables"]
        }
        assert set(before[kind]) == set(expected)
        changed = []
        for name, hashes in before[kind].items():
            if (
                hashlib.sha256(("\n".join(hashes) + "\n").encode()).hexdigest()
                != expected[name]["sha256"]
            ):
                changed.append(name)
        assert set(changed) == (
            set()
            if kind == "native"
            else {"ingest.run", "source.artifact", "source.revision"}
        )
    assert (
        len(before["app"]["ingest.run"]) == 285
        and len(before["app"]["source.artifact"]) == 61
        and len(before["app"]["source.revision"]) == 61
    )
    expected_files = {
        r["path"]: r["sha256"]
        for r in json.loads((DONOR / "file-state-manifest.json").read_text())["files"]
    }
    assert set(expected_files) <= set(before["files"])
    assert [p for p, h in expected_files.items() if before["files"][p] != h] == [
        "out/registries/source_artifacts.json"
    ]
    assert (
        before["files"]["out/registries/source_artifacts.json"]
        == "e4ee8752a14490c5774109bda880653c6f96a7a4752a363e0168c98e90fdf77f"
    )
    assert len(set(before["files"]) - set(expected_files)) == 21


def assert_conservation(before, after):
    assert before["app"] == after["app"] and before["files"] == after["files"]
    # Only mutable native head/source epoch records may replace prior rows.
    mutable = {
        "dungeonmind.knowledge_heads",
        "dungeonmind.knowledge_native_source_authority",
    }
    assert set(before["native"]) == set(after["native"])
    for name, hashes in before["native"].items():
        if name not in mutable:
            assert set(hashes) <= set(after["native"][name]), ("lost native rows", name)
    assert before["other_heads"] == after["other_heads"]
    # Every other World's mutable head is preserved exactly; Elderwyld changes only.
    assert (
        len(after["native"]["dungeonmind.knowledge_heads"])
        == len(before["native"]["dungeonmind.knowledge_heads"])
        == 9
    )


def test_leased_full_world_standing(monkeypatch):
    from apps.live_control_server.integrations.dungeonmind import (
        native_registry_source as native,
    )
    from apps.live_control_server.routes.registry_standing import router

    creds = json.loads((FIXTURE / "clone-connection.json").read_text())
    # Validate exact destination before giving any writer access.
    for key, expected in [
        ("dsn", "benchmark_ingestion_native_e785f5a2e2"),
        ("app_dsn", "benchmark_ingestion_app_e785f5a2e2"),
    ]:
        p = conninfo_to_dict(creds[key])
        assert p["dbname"] == expected and p["port"] == "55447"
    monkeypatch.setattr(
        native.config, "managed_world_data_root", lambda: FIXTURE / "file-state"
    )
    monkeypatch.setattr(
        native.config, "world_graph_authority_database_url", lambda: creds["dsn"]
    )
    monkeypatch.setenv("DMB_AGENT_GRAPH_AUTH_MODE", "local_operator")
    monkeypatch.setenv("DMB_AGENT_GRAPH_AUTH_ENVIRONMENT", "local")
    operator = secrets.token_hex(32)
    monkeypatch.setenv("DMB_AGENT_GRAPH_LOCAL_OPERATOR_TOKEN", operator)
    # Persist a private test signing capability across stage processes, not in the fixture or repository.
    EVIDENCE.mkdir(mode=0o700, exist_ok=True)
    key_path = EVIDENCE / "test-signing-key"
    if not key_path.exists():
        key_path.write_text(secrets.token_hex(32))
        key_path.chmod(0o600)
    monkeypatch.setenv("DMB_GRAPH_REVIEW_PREPARE_BINDING_KEY", key_path.read_text())
    app = FastAPI()
    app.include_router(router)
    client = TestClient(app, client=("127.0.0.1", 45001))
    headers = {"Authorization": "Bearer " + operator}
    api = "/api/live/extract-promote/registry-standing"

    def save(name, value):
        (EVIDENCE / name).write_text(json.dumps(value, indent=2, default=str) + "\n")

    before = snapshot(creds)
    if STAGE == "source":
        request_path = EVIDENCE / "source-request.json"
        if request_path.exists():
            request = json.loads(request_path.read_text())
        else:
            assert_evolved_baseline(before)
            save("baseline.json", before)
            hashes = json.loads(
                (
                    CACHE
                    / "native-review-context-v2/pc-standing-exact-source-spans.json"
                ).read_text()
            )
            request = {
                "managed_world_id": "elderwyld",
                "campaign_id": "longmont-c1",
                "roster_key": "1",
                "operation_id": str(uuid4()),
                "created_at": datetime.now(UTC).isoformat(),
                "expected_parent_revision_id": before["head"],
                "registry_sha256": "f0f49045df06f7baf61aa9c43f3739d16483eeb20ac8ed1bbf29f8209474af25",
                "dossier_sha256": {r["slug"]: r["sha256"] for r in hashes["rows"]},
            }
            save("source-request.json", request)
        response = client.post(api + "/source", json=request, headers=headers)
        save(
            "source-http.json",
            {"status": response.status_code, "body": response.json()},
        )
        assert response.status_code == 200, response.text
        packet = response.json()
        save("source-packet.json", packet)
        after = snapshot(creds)
        assert_conservation(before, after)
        save("after-source.json", after)
        assert len(packet["source_packet"]["rows"]) == 6
        print(
            "SIX SOURCE ADMISSIONS VERIFIED; identity approval remains0/6 pending actual choices."
        )
        return
    # Approval is data from the actual operator, never constructed by this test.
    choices_path = os.environ.get("DMB_STANDING_REVIEWED_CHOICES")
    assert choices_path, "actual reviewed identity choices required"
    review = json.loads(Path(choices_path).read_text())
    assert (
        review.get("approved_by")
        and review.get("authorization_evidence")
        and len(review["choices"]) == 6
    )
    packet = json.loads((EVIDENCE / "source-packet.json").read_text())
    assert (
        review["source_packet_sha256"]
        == hashlib.sha256(
            json.dumps(
                packet["source_packet"],
                sort_keys=True,
                separators=(",", ":"),
                ensure_ascii=False,
            ).encode()
        ).hexdigest()
    )
    payload = {
        "operation_id": review["operation_id"],
        **packet,
        "choices": review["choices"],
    }
    prepared_path = EVIDENCE / "prepared.json"
    if prepared_path.exists():
        prepared = json.loads(prepared_path.read_text())
    else:
        response = client.post(api + "/prepare", json=payload, headers=headers)
        save(
            "prepare-http.json",
            {"status": response.status_code, "body": response.json()},
        )
        assert response.status_code == 200, response.text
        prepared = response.json()
        save("prepared.json", prepared)
    response = client.post(api + "/confirm", json=prepared, headers=headers)
    save("confirm-http.json", {"status": response.status_code, "body": response.json()})
    assert response.status_code == 200, response.text
    committed = response.json()
    after = snapshot(creds)
    assert_conservation(before, after)
    assert len(committed["result"]["assertion_results"]) == 12
    replay = client.post(api + "/confirm", json=prepared, headers=headers)
    assert replay.status_code == 200, replay.text
    assert replay.json()["result"] == committed["result"] and replay.json()["recovered"]
    assert snapshot(creds) == after
    # Ordinary Core read service under Buddy's exact C1 campaign request, not raw-row scoring.
    from graph_memory.vnext.domain_runtime import (
        DungeonBuddyVNextProjectionInput,
        build_dungeonbuddy_read_context,
    )
    from dungeonmind.application.vnext import (
        EntityReadService,
        open_admitted_native_text,
    )

    context, access = native.access_context(native.repository(), "elderwyld")
    read = build_dungeonbuddy_read_context(
        parsed_revision=access.parsed,
        projection_input=DungeonBuddyVNextProjectionInput(
            world_id="elderwyld",
            scope_mode="campaign",
            campaign_id="longmont-c1",
            role="gm",
            revision_id=context["revision_id"],
        ),
        source_reader=access.source_view,
    )
    results = {
        r["client_op_id"]: r["durable_assertion_id"]
        for r in committed["result"]["assertion_results"]
    }
    from fastapi.encoders import jsonable_encoder

    proof = []
    for row in packet["source_packet"]["rows"]:
        assertion = access.parsed.assertions_by_id[results[row["slug"] + ":name"]]
        entity = EntityReadService().get_entity(read, assertion.subject_entity_id)
        ids = {a.assertion_id for a in entity.assertions}
        assert (
            results[row["slug"] + ":name"] in ids
            and results[row["slug"] + ":pc"] in ids
        )
        opened = open_admitted_native_text(access, row["evidence_ref_id"])
        assert opened.status == "available" and opened.body_sha256 == row["sha256"]
        proof.append(
            {
                "slug": row["slug"],
                "entity": jsonable_encoder(entity),
                "source": opened.model_dump(mode="json", exclude={"body_text"}),
            }
        )
    # Preserve current graph meaning, not merely immutable historical rows.
    baseline = json.loads((EVIDENCE / "baseline.json").read_text())
    repo = native.repository()
    original = repo.get_revision("elderwyld", baseline["head"]).graph_payload
    current = repo.get_revision("elderwyld", after["head"]).graph_payload

    def item_hashes(values):
        return {
            hashlib.sha256(
                json.dumps(
                    v, sort_keys=True, separators=(",", ":"), ensure_ascii=False
                ).encode()
            ).hexdigest()
            for v in values
        }

    for kind in ("entities", "assertions", "aliases", "evidence"):
        assert item_hashes(original[kind]) <= item_hashes(current[kind]), kind
    assert current["aliases"] == original["aliases"]
    assert len(current["entities"]) - len(original["entities"]) == 6
    assert len(current["assertions"]) - len(original["assertions"]) == 12
    assert len(current["evidence"]) - len(original["evidence"]) == 6
    for row in packet["source_packet"]["rows"]:
        for suffix in (":name", ":pc"):
            assertion = access.parsed.assertions_by_id[results[row["slug"] + suffix]]
            assert assertion.metadata.temporal_scope.kind == "unknown"
    donor_creds = json.loads((DONOR / "clone-connection.json").read_text())
    donor_parts = conninfo_to_dict(donor_creds["dsn"])
    assert (
        donor_parts["dbname"] == "benchmark_elderwyld_native_d921c3fa59"
        and donor_parts["port"] == "55447"
    )
    with psycopg.connect(
        make_conninfo(donor_creds["dsn"], options="-c default_transaction_read_only=on")
    ) as donor:
        donor.execute("SET TRANSACTION READ ONLY")
        original_other_heads = donor.execute(
            "select space_id,head_revision_id,updated_at::text,schema_version from dungeonmind.knowledge_heads where space_id<>'elderwyld' order by space_id"
        ).fetchall()
    assert after["other_heads"] == original_other_heads
    save(
        "graph-conservation.json",
        {
            "original_revision": baseline["head"],
            "current_revision": after["head"],
            "old_graph_items_preserved": True,
            "other_world_heads_preserved": "8/8",
            "exact_new_entities": 6,
            "exact_new_assertions": 12,
            "exact_new_evidence": 6,
            "aliases_unchanged": True,
            "temporal_bounds_unknown": "12/12",
        },
    )
    save("ordinary-readback.json", proof)
    save("after-confirm.json", after)
    save(
        "acceptance.json",
        {
            "source_admissions": "6/6",
            "reviewed_targets": "6/6",
            "intended_assertions": "12/12",
            "ordinary_scoped_readback": "6/6",
            "exact_retry": True,
            "APP_preserved": True,
            "files_preserved": True,
            "prior_native_rows_preserved": True,
            "full_ingestion_verified": "0/15",
            "provider_calls": 0,
            "head": after["head"],
            "review": review,
        },
    )
